DOCX_MEDIA_TYPE = ("application/vnd.openxmlformats-officedocument."
                   "wordprocessingml.document")


def render(blocks: list[Block], basename: str,
           fmt: str = "docx") -> tuple[bytes, str, str, str]:
    """Return (payload, filename, media type, digest) for the requested format."""
    digest = _digest(blocks)
    if fmt == "docx" and DOCX_AVAILABLE:
        import io
        buf = io.BytesIO()
        render_docx(blocks, digest, buf)
        return buf.getvalue(), f"{basename}.docx", DOCX_MEDIA_TYPE, digest
    document = render_html(blocks, digest, basename.replace("-", " "))
    return (document.encode("utf-8"), f"{basename}.doc",
            "application/msword", digest)
