def _e(v: Any) -> str:
    return html.escape(_txt(v), quote=False)


def render_html(blocks: list[Block], digest: str, title: str) -> str:
    out: list[str] = []
    for block in blocks:
        kind = block[0]
        if kind == "masthead":
            out.append(f"<div class='org'>Criminal Network Analysis System</div>"
                       f"<h1>{_e(block[1])}</h1>"
                       f"<div class='sub'>{_e(block[2])}</div>")
        elif kind in ("h2", "h3"):
            out.append(f"<{kind}>{_e(block[1])}</{kind}>")
        elif kind == "p":
            out.append(f"<p>{_e(block[1])}</p>")
        elif kind == "stmt":
            out.append(f"<p class='stmt'>{_e(block[1])}</p>")
        elif kind == "notice":
            out.append(f"<div class='box'>{_e(block[1])}</div>")
        elif kind == "limit":
            out.append(f"<div class='box warn'>{_e(block[1])}</div>")
        elif kind == "kv":
            rows = "".join(
                f"<tr><td class='k'>{_e(k)}</td>"
                f"<td{' class=mono' if style == 'mono' else ''}>{_e(v)}</td></tr>"
                for k, v, style in block[1])
            out.append(f"<table>{rows}</table>")
        elif kind == "table":
            headers, rows, hi = block[1], block[2], set(block[3] or [])
            head = "".join(f"<th>{_e(h)}</th>" for h in headers)
            body = "".join(
                f"<tr{' class=hi' if i in hi else ''}>"
                + "".join(f"<td>{_e(c)}</td>" for c in row) + "</tr>"
                for i, row in enumerate(rows))
            out.append(f"<table><tr>{head}</tr>{body}</table>")

    foot = (f"<div class='foot'>Document digest (SHA-256): "
            f"<span class='mono'>{digest}</span><br>"
            "This digest is recorded in the CNAS audit ledger at the moment of "
            "export. A report whose digest is absent from the ledger was not "
            "produced by this system.</div>")
    return _HEAD.format(title=_e(title), style=_STYLE) + "".join(out) + foot + "</body></html>"


