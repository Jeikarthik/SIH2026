def case_report(case: dict[str, Any], ego: dict[str, Any],
                findings: list[dict[str, Any]], principal,
                hidden_count: int = 0) -> tuple[list[Block], str]:
    """Full case file: particulars, extracted network, every relevant finding."""
    props = case.get("props", {})
    case_id = case["id"]
    report_id = f"CNAS/RPT/{case_id}/{time.strftime('%Y%m%d-%H%M%S')}"

    blocks: list[Block] = [
        ("masthead", "Case Analysis Report",
         f"{props.get('title', case_id)} ({case_id})"),
        _provenance(principal, report_id),
        NOTICE,
        ("h2", "1. Case particulars"),
        ("kv", [
            ("Case reference", case_id, "mono"),
            ("Title", _txt(props.get("title")), None),
            ("Crime category", _txt(props.get("crime")), None),
            ("District", _txt(props.get("district")), None),
            ("Date opened", _txt(props.get("opened")), None),
            ("Investigating officer", _txt(props.get("officer")), None),
            ("Source record", _txt(case.get("source_record_id")), "mono"),
            ("Access tier of record", _txt(case.get("tier", "standard")), None),
        ]),
    ]
    blocks.extend(_network_blocks(ego, case_id))

    blocks.append(("h2", f"3. Findings on this network ({len(findings)})"))
    if not findings:
        blocks.append(("p", "No detection mechanism returned a finding on this "
                            "network at the access tier applied."))
    else:
        blocks.append(("table", ["Reference", "Finding", "Confidence", "Status"],
                       [[f["finding_id"], f["finding_type"], f"{f['confidence']:.2f}",
                         _txt(f.get("status")).upper()] for f in findings], []))
        for i, f in enumerate(findings, start=1):
            blocks.extend(_finding_blocks(f, number=f"3.{i}"))

    if hidden_count:
        blocks.append(("h2", "4. Withheld at this access tier"))
        blocks.append(("p", f"{hidden_count} record(s) in the system are outside "
                            "the access tier under which this report was produced "
                            "and are neither counted nor described above."))
    return blocks, report_id


def finding_report(f: dict[str, Any], principal) -> tuple[list[Block], str]:
    """One finding, with its complete explainability record."""
    report_id = f"CNAS/RPT/{f['finding_id']}/{time.strftime('%Y%m%d-%H%M%S')}"
    blocks: list[Block] = [
        ("masthead", "Finding Report", f["finding_type"]),
        _provenance(principal, report_id),
        NOTICE,
    ]
    blocks.extend(_finding_blocks(f))
    return blocks, report_id


def queue_report(findings: list[dict[str, Any]], principal,
                 scope: str = "All findings") -> tuple[list[Block], str]:
    """The review queue as filed: summary table, then each record in full."""
    report_id = f"CNAS/RPT/QUEUE/{time.strftime('%Y%m%d-%H%M%S')}"
    counts = {"pending": 0, "confirmed": 0, "rejected": 0}
    for f in findings:
        st = f.get("status", "pending")
        counts[st] = counts.get(st, 0) + 1

    blocks: list[Block] = [
        ("masthead", "Review Queue Report", scope),
        _provenance(principal, report_id, extra=[
            ("Findings in report", len(findings)),
            ("Pending / confirmed / rejected",
             f"{counts['pending']} / {counts['confirmed']} / {counts['rejected']}"),
        ]),
        NOTICE,
        ("h2", "1. Summary"),
        ("table", ["Reference", "Mechanism family", "Finding", "Confidence", "Status"],
         [[f["finding_id"],
           config.MECHANISM_FAMILIES.get(f.get("mechanism_family", ""), ""),
           f["finding_type"], f"{f['confidence']:.2f}",
           _txt(f.get("status")).upper()] for f in findings], []),
        ("h2", "2. Findings in full"),
    ]
    for i, f in enumerate(findings, start=1):
        blocks.extend(_finding_blocks(f, number=f"2.{i}"))
    return blocks, report_id


