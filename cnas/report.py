NAVY = (0x1B, 0x3A, 0x5F)
GREY = (0x44, 0x44, 0x44)
AMBER_BG = "FDF6E6"
HEAD_BG = "E8EAED"
KEY_BG = "F4F5F7"
HI_BG = "EAF0F8"


def _shade(cell, hex_fill: str) -> None:
    el = OxmlElement("w:shd")
    el.set(qn("w:val"), "clear")
    el.set(qn("w:fill"), hex_fill)
    cell._tc.get_or_add_tcPr().append(el)


def _rule(paragraph, size: int = 12, color: str = "1B3A5F") -> None:
    """A horizontal rule, which Word expresses as a bottom paragraph border."""
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), str(size))
    bottom.set(qn("w:space"), "3")
    bottom.set(qn("w:color"), color)
    pbdr.append(bottom)
    paragraph._p.get_or_add_pPr().append(pbdr)


def _run(p, text: str, *, bold=False, size=10.5, color=None, mono=False, caps=False):
    r = p.add_run(text.upper() if caps else text)
    r.bold = bold
    r.font.size = Pt(size)
    r.font.name = "Consolas" if mono else "Calibri"
    if color:
        r.font.color.rgb = RGBColor(*color)
    return r


def _box(doc, text: str, fill: str, bar_color: str | None = None):
    """A callout, which Word does most reliably as a one-cell shaded table."""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    cell = t.cell(0, 0)
    _shade(cell, fill)
    p = cell.paragraphs[0]
    _run(p, text, size=9.5)
    doc.add_paragraph()
    return t


def render_docx(blocks: list[Block], digest: str, path_or_stream) -> None:
    doc = Document()

    sec = doc.sections[0]
    sec.page_height, sec.page_width = Cm(29.7), Cm(21.0)
    sec.top_margin = sec.bottom_margin = Cm(2.0)
    sec.left_margin = sec.right_margin = Cm(1.8)

    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(10.5)

    for block in blocks:
        kind = block[0]

        if kind == "masthead":
            p = doc.add_paragraph()
            _run(p, "Criminal Network Analysis System", bold=True, size=9,
                 color=NAVY, caps=True)
            p = doc.add_paragraph()
            _run(p, block[1], bold=True, size=18)
            p = doc.add_paragraph()
            _run(p, block[2], size=11, color=GREY)
            _rule(p)

        elif kind == "h2":
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(14)
            _run(p, block[1], bold=True, size=13, color=NAVY)
            _rule(p, size=6, color="9AA0A6")

        elif kind == "h3":
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(10)
            _run(p, block[1], bold=True, size=11)

        elif kind == "p":
            _run(doc.add_paragraph(), block[1])

        elif kind == "stmt":
            p = doc.add_paragraph()
            _run(p, block[1], size=11.5)

        elif kind == "notice":
            _box(doc, block[1], KEY_BG)

        elif kind == "limit":
            _box(doc, block[1], AMBER_BG)

        elif kind == "kv":
            rows = block[1]
            t = doc.add_table(rows=len(rows), cols=2)
            t.style = "Table Grid"
            for i, (k, v, style) in enumerate(rows):
                kc, vc = t.cell(i, 0), t.cell(i, 1)
                kc.width, vc.width = Cm(5.2), Cm(12.0)
                _shade(kc, KEY_BG)
                _run(kc.paragraphs[0], _txt(k), size=9.5, bold=True)
                _run(vc.paragraphs[0], _txt(v), size=9.5, mono=(style == "mono"))
            doc.add_paragraph()

        elif kind == "table":
            headers, rows, hi = block[1], block[2], set(block[3] or [])
            t = doc.add_table(rows=len(rows) + 1, cols=len(headers))
            t.style = "Table Grid"
            for j, h in enumerate(headers):
                cell = t.cell(0, j)
                _shade(cell, HEAD_BG)
                _run(cell.paragraphs[0], h, bold=True, size=9, caps=True)
            for i, row in enumerate(rows, start=1):
                for j, val in enumerate(row):
                    cell = t.cell(i, j)
                    if (i - 1) in hi:
                        _shade(cell, HI_BG)
                    _run(cell.paragraphs[0], _txt(val), size=9)
            doc.add_paragraph()

    p = doc.add_paragraph()
    _rule(p, size=6, color="9AA0A6")
    p = doc.add_paragraph()
    _run(p, "Document digest (SHA-256): ", size=8.5, color=GREY)
    _run(p, digest, size=8.5, mono=True, color=GREY)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    _run(p, "This digest is recorded in the CNAS audit ledger at the moment of "
            "export. A report whose digest is absent from the ledger was not "
            "produced by this system.", size=8.5, color=GREY)

    doc.save(path_or_stream)


