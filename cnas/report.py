def _provenance(principal, report_id: str,
                extra: Iterable[tuple[str, Any]] = ()) -> Block:
    rows = [
        ("Report reference", report_id, "mono"),
        ("Generated", time.strftime("%d %B %Y, %H:%M"), None),
        ("Generated by", f"{principal.display} — {principal.unit}", None),
        ("Access tier applied", ", ".join(principal.tiers), None),
        ("Classification", "Prototype / synthetic data", None),
    ]
    rows.extend((k, _txt(v), None) for k, v in extra)
    return ("kv", rows)


NOTICE = ("notice",
          "Data notice. This report is produced from synthetic demonstration "
          "data. It does not describe any real person, case, account, vehicle "
          "or telephone number. Findings are analytical products and are not "
          "evidence in themselves; each states the limitations under which it "
          "was produced.")


def _finding_blocks(f: dict[str, Any], number: str | None = None) -> list[Block]:
    head = f"{number}. {f['finding_type']}" if number else f["finding_type"]
    out: list[Block] = [("h2", head), ("stmt", f["statement"])]

    out.append(("kv", [
        ("Finding reference", f["finding_id"], "mono"),
        ("Mechanism family", config.MECHANISM_FAMILIES.get(
            f.get("mechanism_family", ""), f.get("mechanism_family", "")), None),
        ("Mechanism", f["mechanism"], "mono"),
        ("Mechanism version", _txt(f.get("model_version")), "mono"),
        ("Parameters used", _params(f.get("mechanism_params")), "mono"),
        ("Confidence", f"{f['confidence']:.3f}", None),
        ("Confidence means", _txt(f.get("confidence_meaning")), None),
        ("Access tier", _txt(f.get("tier", "standard")), None),
        ("Status", _txt(f.get("status", "pending")).upper(), None),
    ]))

    ev = f.get("evidence") or []
    if ev:
        out.append(("h3", f"Evidence ({len(ev)} record{'' if len(ev) == 1 else 's'})"))
        out.append(("table",
                    ["Record", "Type", "Role in the finding", "Source record"],
                    [[_txt(e.get("node_id")), _txt(e.get("label")),
                      _txt(e.get("role")), _txt(e.get("source_record_id"))] for e in ev],
                    []))

    merges = f.get("contributing_merges") or []
    if merges:
        out.append(("h3", "Entity resolution decisions behind this finding"))
        out.append(("p", "If one of these merges is incorrect, this finding is "
                         "incorrect. Each is reversible."))
        out.append(("table", ["Merge reference"], [[_txt(m)] for m in merges], []))

    out.extend(_mechanism_blocks(f))

    out.append(("h3", "Known limitations"))
    out.append(("limit", _txt(f.get("limitations"))))

    out.append(("h3", "Investigator decision"))
    if f.get("status") != "pending":
        out.append(("kv", [
            ("Decision", _txt(f.get("status")).upper(), None),
            ("Decided by", _txt(f.get("decided_by")), None),
            ("Decided at", _txt(f.get("decided_at")).replace("T", " "), None),
            ("Reason recorded", _txt(f.get("decision_reason")), None),
        ]))
    else:
        out.append(("p", "Not yet reviewed. This finding is pending human "
                         "confirmation and must not be acted on as a conclusion."))
    return out


def _mechanism_blocks(f: dict[str, Any]) -> list[Block]:
    """The per-mechanism working, so the report stands on its own off-screen."""
    x = f.get("extra") or {}
    m = f.get("mechanism")

    if m == "rule.structuring" and x.get("deposits"):
        rows = [[_txt(d.get("from")), _inr(d.get("amount")),
                 _txt(d.get("when")).replace("T", " ")[:16], _txt(d.get("channel"))]
                for d in x["deposits"]]
        rows.append(["Total", _inr(x.get("total")),
                     f"over {_txt(x.get('window_hours'))} hours", ""])
        return [("h3", "Deposits that satisfied the rule"),
                ("table", ["From", "Amount", "When", "Channel"], rows,
                 list(range(len(x["deposits"]))))]

    if m == "statistical.benford" and x.get("suspect"):
        s, c = x["suspect"], x.get("control") or {}
        rows = [[str(i + 1), _txt(o), _txt(s["expected"][i])]
                for i, o in enumerate(s.get("observed", []))]
        return [
            ("h3", "First-digit distribution"),
            ("table", ["Leading digit", "Observed", "Benford expected"], rows, []),
            ("kv", [
                ("Sample size (n)", _txt(s.get("n")), None),
                ("Orders of magnitude", _txt(s.get("orders_of_magnitude")), None),
                ("Mean absolute deviation", _txt(s.get("mad")), None),
                ("Chi-square", f"{s.get('chi2')} (critical "
                               f"{s.get('critical_value_chi2_p01')} at p=0.01)", None),
                ("Verdict", _txt(s.get("verdict")), None),
                ("Control group", f"{_txt(c.get('verdict', 'n/a'))} (n={c.get('n', 0)})", None),
            ])]

    if m == "timeseries.cusum" and x.get("series"):
        return [("h3", "Change-point detection"), ("kv", [
            ("Baseline mean daily credit", _inr(x.get("mu0")), None),
            ("Mean after change point", _inr(x.get("post_change_mean")), None),
            ("Change detected on", _txt(x.get("alarm_date")), None),
            ("Decision limit (h)", _txt(x.get("h")), None),
            ("Days observed", str(len(x.get("series", []))), None),
        ])]

    if m == "vector.mo_similarity" and x.get("narratives"):
        out = [("h3", "Comparison"), ("kv", [
            ("Structured feature similarity", _txt(x.get("feature_similarity")), None),
            ("Narrative text similarity", _txt(x.get("text_similarity")), None),
            ("Combined score", _txt(x.get("combined")), None),
            ("Shared entities", ", ".join(x.get("shared_entities") or []) or "none", None),
        ]), ("table", ["Case", "Narrative as filed"],
             [[k, v] for k, v in x["narratives"].items()], [])]
        if x.get("agreeing_features"):
            out.append(("table", ["Attribute", "Value in both cases"],
                        [[_txt(k), _txt(v)] for k, v in x["agreeing_features"].items()], []))
        return out

    if m == "structural.community_bridge":
        if x.get("top_by_betweenness"):
            ri = x.get("removal_impact") or {}
            subjects = set(f.get("subject_ids") or [])
            rows, hi = [], []
            for i, r in enumerate(x["top_by_betweenness"]):
                rows.append([_txt(r.get("display")), _txt(r.get("label")),
                             _txt(r.get("betweenness"))])
                if r.get("id") in subjects:
                    hi.append(i)
            return [("h3", "Betweenness ranking in the bounded subgraph"),
                    ("table", ["Record", "Type", "Betweenness"], rows, hi),
                    ("kv", [
                        ("Communities detected", _txt(x.get("n_communities")), None),
                        ("Communities spanned", _txt(x.get("communities_spanned")), None),
                        ("Components before removal", _txt(ri.get("components_before")), None),
                        ("Components after removal", _txt(ri.get("components_after"))
                         + (" — removal splits the network" if ri.get("splits") else ""), None),
                    ])]
        if x.get("path"):
            rows = [[str(i + 1), _txt(n.get("display")), _txt(n.get("label"))]
                    for i, n in enumerate(x["path"].get("nodes", []))]
            return [("h3", "Traced path"),
                    ("table", ["#", "Record", "Type"], rows, list(range(len(rows))))]

    if f.get("mechanism_family") == "er" and (x.get("merge") or x.get("merges")):
        out: list[Block] = []
        for mg in [g for g in (x.get("merges") or [x.get("merge")]) if g and g.get("fields")]:
            rows = [[_txt(fl.get("field")), _score(fl.get("score")),
                     "deterministic" if fl.get("weight") is None else _txt(fl.get("weight")),
                     _txt(fl.get("note"))] for fl in mg["fields"]]
            th = mg.get("thresholds") or {}
            out.extend([
                ("h3", f"Field agreement — {mg.get('left_display')} vs {mg.get('right_display')}"),
                ("table", ["Field", "Score", "Weight", "Note"], rows, []),
                ("kv", [
                    ("Method", _txt(mg.get("method")), None),
                    ("Overall score", _txt(mg.get("score")), None),
                    ("Decision", _txt(mg.get("decision")), None),
                    ("Thresholds", f"review at {th.get('tau_low')}, "
                                   f"auto-merge at {th.get('tau_high')}", None),
                ]),
                ("limit", _txt(mg.get("rationale"))),
            ])
        return out
    return []


def _network_blocks(ego: dict[str, Any], case_id: str) -> list[Block]:
    by_label: dict[str, int] = {}
    for n in ego.get("nodes", []):
        by_label[n["label"]] = by_label.get(n["label"], 0) + 1
    by_type: dict[str, int] = {}
    for e in ego.get("edges", []):
        by_type[e["type"]] = by_type.get(e["type"], 0) + 1

    return [
        ("h2", "2. Network extracted around this case"),
        ("kv", [
            ("Centred on", case_id, "mono"),
            ("Traversal depth", f"{ego.get('hops', 2)} hops", None),
            ("Records returned", str(len(ego.get("nodes", []))), None),
            ("Relationships returned", str(len(ego.get("edges", []))), None),
            ("Bound applied", f"{ego.get('cap')} nodes"
             + (" (reached)" if ego.get("truncated") else " (not reached)"), None),
        ]),
        ("h3", "Composition"),
        ("table", ["Record type", "Count"],
         [[k, str(v)] for k, v in sorted(by_label.items(), key=lambda kv: -kv[1])], []),
        ("h3", "Relationships"),
        ("table", ["Relationship", "Count"],
         [[k, str(v)] for k, v in sorted(by_type.items(), key=lambda kv: -kv[1])], []),
        ("h3", "Records in the extracted network"),
        ("table", ["Reference", "Type", "Identifier", "Source record"],
         [[n["id"], n["label"], n["display"], n["source_record_id"]]
          for n in sorted(ego.get("nodes", []), key=lambda n: (n["label"], n["id"]))], []),
    ]


