"""Report generation.

A report is built once as a list of content blocks and then rendered twice
over: to a real Word document (.docx) when python-docx is installed, and to
Word-flavoured HTML (.doc) otherwise, which Word, LibreOffice and Google Docs
all open. One content model, two encodings, so the two can never drift.

Every report carries the tier it was produced under, the officer who produced
it, and a SHA-256 digest of its content. The digest is taken over the content
model rather than over either encoding, so the same report digests identically
in both formats, and it is written to the audit ledger at export time: a
printed report can be checked against the ledger entry that recorded it.
"""
from __future__ import annotations

import hashlib
import html
import json
import time
from typing import Any, Iterable

from . import config

try:  # A real .docx is preferable; the HTML fallback keeps the demo running.
    import docx  # noqa: F401
    from docx import Document
    from docx.enum.section import WD_ORIENT  # noqa: F401
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt, RGBColor
    DOCX_AVAILABLE = True
except ImportError:  # pragma: no cover - exercised only on a bare install
    DOCX_AVAILABLE = False


# --------------------------------------------------------------------------
# Content model
#
# Every block is a tuple whose first element names its kind:
#   ("masthead", title, subtitle)
#   ("h2" | "h3", text)
#   ("p" | "stmt" | "notice" | "limit", text)
#   ("kv", [(key, value, style|None), ...])
#   ("table", [headers], [[cells], ...], [highlighted row indexes])
#   ("digest", hex)
# `style` is "mono" or None. Nothing in the model is markup.
# --------------------------------------------------------------------------

Block = tuple


def _txt(v: Any) -> str:
    return "" if v is None else str(v)


def _inr(n: Any) -> str:
    try:
        return "Rs " + f"{int(round(float(n))):,}"
    except (TypeError, ValueError):
        return _txt(n)


def _score(v: Any) -> str:
    if v is None:
        return "—"
    try:
        return f"{float(v):.2f}"
    except (TypeError, ValueError):
        return _txt(v)


def _params(d: dict[str, Any] | None) -> str:
    return "; ".join(f"{k.replace('_', ' ')} = {v}" for k, v in (d or {}).items())


def _digest(blocks: list[Block]) -> str:
    payload = json.dumps(blocks, ensure_ascii=False, sort_keys=True, default=str)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


